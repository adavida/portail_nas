const toLang = (v: string): Lang => (v === "fr" ? "fr" : "en");

export const lang = writable<string>(toLang(env.appLang));

export function translate(
  key: string,
  params?: Record<string, string>,
): string {
  let s = locales[toLang(get(lang))][key] ?? key;
  if (params)
    for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(v);
  return s;
}

export const t = derived(lang, () => translate);
